import "dotenv/config";
import pg from "pg";
import { createApp } from "./app.js";
const port=Number(process.env.PORT||8080);
const token=process.env.SRC_ADMIN_TOKEN||"";
if(!process.env.DATABASE_URL)throw new Error("DATABASE_URL must be configured");
if(process.env.NODE_ENV!=="production"&&token.length<32)throw new Error("Set SRC_ADMIN_TOKEN to 32+ random chars for local development");
if(process.env.NODE_ENV==="production"&&process.env.SRC_PAYMENTS_ENABLED==="true"&&(!process.env.RAZORPAY_WEBHOOK_SECRET||!process.env.SMTP_HOST))throw new Error("Live payments require verified webhook and support email configuration");
const pool=new pg.Pool({connectionString:process.env.DATABASE_URL});
createApp(pool,{adminToken:token,corsOrigin:process.env.CORS_ORIGIN||"https://srcenterprises.in"}).listen(port,()=>console.log("SRC API listening on",port));
